    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        try {
            String appointmentId = jTextField3.getText().trim();
            String total = jTextField4.getText().trim();
            String paid = jTextField5.getText().trim();
            String balance = jTextField6.getText().trim();
            String paymentMethod = jComboBox4.getSelectedItem().toString();

            if (appointmentId.isEmpty() || total.isEmpty() || paymentMethod.equals("Select")) {
                javax.swing.JOptionPane.showMessageDialog(this, "Please fill all required fields!");
                return;
            }

            String paymentId = billingMap.get(paymentMethod);

            // Get patient & staff from appointment
            ResultSet rs = MySQL.execute("SELECT patient_patient_nic, staff_has_hospital_id FROM appointment WHERE id='" + appointmentId + "'");
            if (!rs.next()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Invalid Appointment ID!");
                return;
            }
            String patientNIC = rs.getString("patient_patient_nic");
            String staffId = rs.getString("staff_has_hospital_id");

            // Insert into billing
            MySQL.execute("INSERT INTO billing (appointment_id, staff_id, total_amount, date, payment_method_id, patient_patient_nic) "
                    + "VALUES ('" + appointmentId + "', '" + staffId + "', '" + total + "', NOW(), '" + paymentId + "', '" + patientNIC + "')");

            javax.swing.JOptionPane.showMessageDialog(this, "Bill saved successfully!");

            // Clear fields
            jTextField3.setText("");
            jTextField4.setText("");
            jTextField5.setText("");
            jTextField6.setText("");
            ((javax.swing.table.DefaultTableModel) jTable1.getModel()).setRowCount(0);

        } catch (Exception e) {
            e.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton2ActionPerformed

