// 1. Component
interface BillComponent {

    double getTotal();

    void display();
}

// 2. Leaf - Medicine charge
class MedicineCharge implements BillComponent {

    private String medicineName;
    private double unitPrice;
    private int dosage;
    private int days;

    public MedicineCharge(String medicineName, double unitPrice, int dosage, int days) {
        this.medicineName = medicineName;
        this.unitPrice = unitPrice;
        this.dosage = dosage;
        this.days = days;
    }

    @Override
    public double getTotal() {
        return unitPrice * dosage * days;
    }

    @Override
    public void display() {
        System.out.println(medicineName + " : " + getTotal());
    }
}

// 3. Leaf - Consultation
class ConsultationCharge implements BillComponent {

    private double fee;

    public ConsultationCharge(double fee) {
        this.fee = fee;
    }

    @Override
    public double getTotal() {
        return fee;
    }

    @Override
    public void display() {
        System.out.println("Consultation : " + fee);
    }
}

// 4. Composite - Whole Bill
class BillingComposite implements BillComponent {

    private java.util.List<BillComponent> components = new java.util.ArrayList<>();

    public void add(BillComponent c) {
        components.add(c);
    }

    public void remove(BillComponent c) {
        components.remove(c);
    }

    @Override
    public double getTotal() {
        return components.stream().mapToDouble(BillComponent::getTotal).sum();
    }

    @Override
    public void display() {
        for (BillComponent c : components) {
            c.display();
        }
        System.out.println("TOTAL BILL: " + getTotal());
    }
}

