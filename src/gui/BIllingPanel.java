    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // Get values from fields
        try {
            String appointmentId = jTextField3.getText().trim();
            if (appointmentId.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Enter Appointment ID!");
                return;
            }

            // Clear old table data
            javax.swing.table.DefaultTableModel dtm = (javax.swing.table.DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);

            // Composite Bill
            BillingComposite bill = new BillingComposite();
            HashSet<Object> addedMedicines = new HashSet<Object>(); // to avoid duplicates

            // Load Medicine History + Prices (distinct to prevent duplicates)
            ResultSet rs = MySQL.execute(
                    "SELECT DISTINCT m.medicine, m.price, phm.dosage, phm.for_days, p.patient_nic "
                    + "FROM medicine_history mh "
                    + "INNER JOIN patient_has_medicine phm ON mh.id = phm.medicine_history_id "
                    + "INNER JOIN appointment a ON a.id = mh.appointment_id "
                    + "INNER JOIN patient p ON p.patient_nic = a.patient_patient_nic "
                    + "INNER JOIN medicine m ON m.id = phm.medicine_id "
                    + "WHERE mh.appointment_id = '" + appointmentId + "'"
            );

            String patientNIC = null;
            while (rs.next()) {
                String med = rs.getString("medicine");

                if (addedMedicines.contains(med)) {
                    continue; // Skip if already added
                }
                addedMedicines.add(med);

                double price = rs.getDouble("price");
                int dosage = rs.getInt("dosage");
                int days = rs.getInt("for_days");
                patientNIC = rs.getString("patient_nic");

                MedicineCharge mc = new MedicineCharge(med, price, dosage, days);
                bill.add(mc);

                dtm.addRow(new Object[]{
                    appointmentId,
                    patientNIC,
                    med,
                    days,
                    dosage,
                    mc.getTotal()
                });
            }

            // Load Consultation Fee
            ResultSet rs2 = MySQL.execute("SELECT price FROM appointment WHERE id='" + appointmentId + "'");
            if (rs2.next()) {
                double fee = rs2.getDouble("price");
                ConsultationCharge cc = new ConsultationCharge(fee);
                bill.add(cc);

                dtm.addRow(new Object[]{
                    appointmentId,
                    patientNIC,
                    "Consultation",
                    "-",
                    "-",
                    fee
                });
            }

            // Show Total
            jTextField4.setText(String.valueOf(bill.getTotal()));

        } catch (Exception e) {
            e.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Error loading bill data:\n" + e.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

